package com.liferay.document.library.uad.anonymizer;

import com.liferay.asset.kernel.model.AssetEntry;
import com.liferay.asset.kernel.service.AssetEntryLocalService;
import com.liferay.document.library.kernel.model.DLFileEntryFriendlyURL;
import com.liferay.document.library.kernel.service.DLFileEntryFriendlyURLLocalService;
import com.liferay.document.library.uad.constants.DLUADConstants;
import com.liferay.portal.kernel.dao.orm.ActionableDynamicQuery;
import com.liferay.portal.kernel.exception.PortalException;
import com.liferay.portal.kernel.model.User;
import com.liferay.user.associated.data.anonymizer.DynamicQueryUADAnonymizer;

import org.osgi.service.component.annotations.Reference;

/**
 * Provides the base implementation for the dl file entry friendly url UAD anonymizer.
 *
 * <p>
 * This implementation exists only as a container for the default methods
 * generated by ServiceBuilder. All custom service methods should be put in
 * {@link DLFileEntryFriendlyURLUADAnonymizer}.
 * </p>
 *
 * @author Brian Wing Shun Chan
 * @generated
 */
public abstract class BaseDLFileEntryFriendlyURLUADAnonymizer
	extends DynamicQueryUADAnonymizer<DLFileEntryFriendlyURL> {

	@Override
	public void autoAnonymize(
			DLFileEntryFriendlyURL dlFileEntryFriendlyURL, long userId,
			User anonymousUser)
		throws PortalException {

		if (dlFileEntryFriendlyURL.getUserId() == userId) {
			dlFileEntryFriendlyURL.setUserId(anonymousUser.getUserId());
			dlFileEntryFriendlyURL.setUserName(anonymousUser.getFullName());

			autoAnonymizeAssetEntry(dlFileEntryFriendlyURL, anonymousUser);
		}

		dlFileEntryFriendlyURLLocalService.updateDLFileEntryFriendlyURL(
			dlFileEntryFriendlyURL);
	}

	@Override
	public void delete(DLFileEntryFriendlyURL dlFileEntryFriendlyURL)
		throws PortalException {

		dlFileEntryFriendlyURLLocalService.deleteDLFileEntryFriendlyURL(
			dlFileEntryFriendlyURL);
	}

	@Override
	public Class<DLFileEntryFriendlyURL> getTypeClass() {
		return DLFileEntryFriendlyURL.class;
	}

	protected void autoAnonymizeAssetEntry(
		DLFileEntryFriendlyURL dlFileEntryFriendlyURL, User anonymousUser) {

		AssetEntry assetEntry = fetchAssetEntry(dlFileEntryFriendlyURL);

		if (assetEntry != null) {
			assetEntry.setUserId(anonymousUser.getUserId());
			assetEntry.setUserName(anonymousUser.getFullName());

			assetEntryLocalService.updateAssetEntry(assetEntry);
		}
	}

	@Override
	protected ActionableDynamicQuery doGetActionableDynamicQuery() {
		return dlFileEntryFriendlyURLLocalService.getActionableDynamicQuery();
	}

	@Override
	protected String[] doGetUserIdFieldNames() {
		return DLUADConstants.USER_ID_FIELD_NAMES_DL_FILE_ENTRY_FRIENDLY_URL;
	}

	protected AssetEntry fetchAssetEntry(
		DLFileEntryFriendlyURL dlFileEntryFriendlyURL) {

		return assetEntryLocalService.fetchEntry(
			DLFileEntryFriendlyURL.class.getName(),
			dlFileEntryFriendlyURL.getFileEntryFriendlyURLId());
	}

	@Reference
	protected AssetEntryLocalService assetEntryLocalService;

	@Reference
	protected DLFileEntryFriendlyURLLocalService
		dlFileEntryFriendlyURLLocalService;

}